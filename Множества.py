'''
Множества (set) неупорядоченный набор уникальных объектов (любые неизменяемые типы данных)

  множество относится к хэш таблицам по структуре данных
  список относится к массиву (в разрезе структуры данных)
'''

ls = [22, 22, 22, 33, 44]
st = set(ls)
print(st)
st.clear()
st = {22, 33, 44}
print(st)

st.add(100) #""" добавить элемент (как append в строках) один объект, """
st.update({2, 3}) # добавляет несколько объектов в само множество
print(st)
n = st.pop() # удаляет элемент по индексу
st.remove(3) # удаляет если находит, если не находит, то ошибка
st.discard(3) # удаляет если находит, если не находит, то ничего не происходит
print(n)



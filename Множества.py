st1 = {3, 4, 33}
st2 = {3, 4, 44}

res = st1.union(st2) # объеденение множеств 1й способ
res = st1 | st2 # объеденение множеств 2й способ

res = st1.intersection(st2) # пересечение множеств 1й способ
res = st1 & st2 # пересечение множеств 2й способ

res = st1.difference(st2) # Вычитание множеств 1й способ
res = st2 - st1  # Вычитание множеств 2й способ

print(res)

res = st1.symmetric_difference(st2) # Симметричное вычитание
res = st1 ^ st2
print(res)

st3 = {3, 4}
print(st3.issubset(st2)) # Подмножество
print(st1.issuperset(st3)) # Супермножество


